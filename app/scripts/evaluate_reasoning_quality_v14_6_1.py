"""v14.6.1: conservative, repository-agnostic paired reasoning diagnostics.

No LLM calls, retriever changes, or correctness claims. Optional dataset supplies
structural references generated by v14.6, which are not independently verified.
"""
from __future__ import annotations
import argparse
import json
import re
from collections import Counter
from pathlib import Path
from typing import Any

EDGE = re.compile(r"STATIC CALL EVIDENCE[^:]*:\s*(\S+?)\s*->\s*(\S+?);", re.I)
NEGATION = re.compile(r"\b(no (?:direct |verified |static[ -]?)?(?:call|edge|relationship|evidence)|insufficient evidence|cannot (?:confirm|determine|assert|verify)|unable to (?:confirm|verify)|does not (?:contain|show|establish)|not enough evidence|no evidence)\b", re.I)
AFFIRM = re.compile(r"\b(directly calls|directly invokes|direct static (?:call|relationship)|static call relationship|static.call edge|calls|invokes|instantiates|constructs)\b", re.I)
OVERCLAIM = re.compile(r"\b(no other (?:indirect|dynamic|runtime|call) (?:call )?paths?|cannot (?:ever|possibly)|impossible (?:to|for)|guaranteed (?:at runtime|to execute)|always executed|compile.time)\b", re.I)
UNCERTAINTY = re.compile(r"\b(static analysis|static.call|not verified runtime|runtime (?:execution|behavior)|dynamic dispatch|reflection|cannot (?:confirm|verify|rule out)|insufficient evidence|provided evidence|evidence (?:does not|cannot))\b", re.I)

def load(path: str | Path) -> Any:
    return json.loads(Path(path).read_text(encoding='utf-8-sig'))

def symbols(question: str) -> list[str]:
    return re.findall(r"[A-Za-z0-9_./\\-]+\.py::[A-Za-z_][A-Za-z_0-9]*", question)

def relation_from_case(case: dict, dataset_case: dict | None) -> dict:
    meta = (dataset_case or {}).get('review_metadata', {})
    ref = meta.get('structural_reference') or {}
    names = symbols(case.get('question', ''))
    return {'relationship': ref.get('relationship'), 'source': ref.get('source') or (names[0] if names else None),
            'target': ref.get('target') or (names[1] if len(names) > 1 else None),
            'origin': 'dataset_structural_reference' if ref else 'question_only_unlabeled'}

def assess_variant(variant: dict, relation: dict) -> dict:
    answer = variant.get('answer')
    if not isinstance(answer, str) or not answer.strip():
        return {'answer_available': False, 'error': variant.get('error'), 'manual_review_required': True}
    src, dst = relation['source'], relation['target']
    mentioned = {key: bool(value and (value in answer or value.split('::')[-1] in answer)) for key, value in [('source', src), ('target', dst)]}
    negatives = [m.group(0) for m in NEGATION.finditer(answer)]
    affirmatives = [m.group(0) for m in AFFIRM.finditer(answer)]
    risks = [m.group(0) for m in OVERCLAIM.finditer(answer)]
    return {'answer_available': True, 'answer_characters': len(answer),
            'source_symbol_mentioned': mentioned['source'], 'target_symbol_mentioned': mentioned['target'],
            'negative_evidence_phrases': negatives[:8], 'affirmative_call_phrases': affirmatives[:8],
            'possible_overclaim_phrases': risks[:8], 'uncertainty_language_present': bool(UNCERTAINTY.search(answer)),
            'llm_ms': variant.get('llm_ms'), 'evidence_count': variant.get('evidence_count'),
            'manual_review_required': True}

def evaluate(comparison: dict, dataset: dict | list | None = None) -> dict:
    dataset_cases = (dataset.get('cases', dataset) if isinstance(dataset, dict) else dataset) or []
    index = {x['id']: x for x in dataset_cases if isinstance(x, dict) and 'id' in x}
    results = []
    for case in comparison.get('cases', []):
        ref = relation_from_case(case, index.get(case['id']))
        additions = case.get('enhanced', {}).get('added_evidence') or []
        edges = [(m.group(1), m.group(2)) for item in additions for m in EDGE.finditer(str(item.get('content', '')))]
        direct = bool(ref['source'] and ref['target'] and (ref['source'], ref['target']) in edges)
        baseline = assess_variant(case.get('baseline', {}), ref)
        enhanced = assess_variant(case.get('enhanced', {}), ref)
        label = ref['relationship']
        flags = []
        if label == 'resolved_static_call' and not direct:
            flags.append('expected_resolved_edge_missing_from_enrichment')
        if label == 'resolved_static_call':
            for name, obj in [('baseline', baseline), ('enhanced', enhanced)]:
                if obj.get('negative_evidence_phrases'):
                    flags.append(f'{name}_negative_or_uncertain_language_on_resolved_edge_review')
        if label == 'no_direct_resolved_edge' and direct:
            flags.append('unexpected_direct_edge_in_enrichment_review')
        for name, obj in [('baseline', baseline), ('enhanced', enhanced)]:
            if obj.get('possible_overclaim_phrases'):
                flags.append(f'{name}_possible_overclaim_review')
            if not obj.get('answer_available'):
                flags.append(f'{name}_missing_answer')
        if not label:
            flags.append('structural_reference_not_supplied')
        results.append({'id': case.get('id'), 'question': case.get('question'), 'repository_id': case.get('repository_id'),
                        'structural_reference': ref, 'added_architecture_records': len(additions),
                        'parsed_architecture_edges': len(edges), 'exact_requested_edge_in_added_evidence': direct,
                        'baseline': baseline, 'enhanced': enhanced, 'review_flags': flags,
                        'review_priority': 'high' if flags else 'standard',
                        'human_review': {'baseline_correct': None, 'enhanced_correct': None,
                                         'unsupported_claims': None, 'notes': ''}})
    count = len(results)
    labels = Counter(x['structural_reference']['relationship'] or 'unlabeled' for x in results)
    flags = Counter(f for x in results for f in x['review_flags'])
    summary = {'cases': count, 'structural_reference_counts': dict(labels),
               'cases_with_added_architecture_evidence': sum(x['added_architecture_records'] > 0 for x in results),
               'resolved_edge_cases': labels['resolved_static_call'],
               'resolved_edge_cases_with_exact_edge_in_enrichment': sum(x['structural_reference']['relationship'] == 'resolved_static_call' and x['exact_requested_edge_in_added_evidence'] for x in results),
               'cases_flagged_for_priority_review': sum(bool(x['review_flags']) for x in results),
               'flag_counts': dict(flags),
               'baseline_answers_available': sum(x['baseline'].get('answer_available', False) for x in results),
               'enhanced_answers_available': sum(x['enhanced'].get('answer_available', False) for x in results),
               'baseline_total_llm_ms': round(sum(x['baseline'].get('llm_ms') or 0 for x in results), 3),
               'enhanced_total_llm_ms': round(sum(x['enhanced'].get('llm_ms') or 0 for x in results), 3),
               'automatic_answer_correctness': None}
    return {'schema_version': '14.6.1', 'methodology': 'Deterministic evidence and answer-text diagnostics; NOT an answer correctness judge.',
            'limitations': ['Structural references are dataset labels, not independent ground truth.',
                            'Regex checks are triage signals and can produce false positives or negatives.',
                            'A missing static edge does not prove no runtime call exists.',
                            'Source-code review is required for correctness, hallucinations, and negative claims.',
                            'Paired LLM output is stochastic; one run cannot establish generalization.'],
            'summary': summary, 'cases': results}

def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--comparison', required=True)
    parser.add_argument('--dataset', help='Optional v14.6 dataset with structural references')
    parser.add_argument('--output', default='data/evaluation/v14_6_1_quality_results.json')
    parser.add_argument('--summary-output', default='data/evaluation/v14_6_1_quality_summary.json')
    args = parser.parse_args()
    report = evaluate(load(args.comparison), load(args.dataset) if args.dataset else None)
    for path, obj in [(args.output, report), (args.summary_output, report['summary'])]:
        target = Path(path)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(obj, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    print(json.dumps(report['summary'], indent=2))

if __name__ == '__main__':
    main()
